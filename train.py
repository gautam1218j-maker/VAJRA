"""
VAJRA Nowcasting — Training loop
=================================
Wires DB-backed sequences -> model.py. Uses the starter archive at
data/starter_dataset/ (generated by generate_starter_dataset.py).
"""

import torch
from pathlib import Path
from torch.utils.data import DataLoader

from model import NowcastNet, nowcast_loss
from normalization import load_normalization_stats, CHANNEL_ORDER
import db

# Radar reflectivity (dBZ) is channel 0 — pull its real archive-derived
# mean/std rather than hardcoding a guess that will silently drift out of
# sync with norm_stats.json as the dataset changes.
_REFLECT_CHANNEL = CHANNEL_ORDER.index("radar_dbz")
_channel_means, _channel_stds = load_normalization_stats()
REFLECT_MEAN = float(_channel_means[_REFLECT_CHANNEL])
REFLECT_STD = float(_channel_stds[_REFLECT_CHANNEL])


PROJECT_DIR = Path(__file__).resolve().parent
DEFAULT_DATA_DIR = PROJECT_DIR / "data" / "starter_dataset"
DEFAULT_DB_URL = f"sqlite:///{(DEFAULT_DATA_DIR / 'vajra.sqlite3').as_posix()}"


def train(epochs=5, batch_size=4, lr=1e-3, device=None, data_dir=None, db_url=None):
    device = device or ("cuda" if torch.cuda.is_available() else "cpu")
    data_dir = data_dir or DEFAULT_DATA_DIR
    db_url = db_url or DEFAULT_DB_URL

    # Initialize the archive database
    db.init_db(db_url, data_dir)

    # Use the DB-backed dataset (train/val/test splits are in the DB)
    dataset = db.DBSequenceDataset(split="train")
    loader = DataLoader(dataset, batch_size=batch_size, shuffle=True)

    model = NowcastNet(in_channels=5, hidden_ch=32, output_steps=18).to(device)
    optim = torch.optim.Adam(model.parameters(), lr=lr)

    for epoch in range(epochs):
        model.train()
        running = 0.0
        for X, y_dbz, y_lightning in loader:
            X, y_dbz, y_lightning = X.to(device), y_dbz.to(device), y_lightning.to(device)
            optim.zero_grad()
            pred_dbz, pred_lightning = model(X)
            loss, parts = nowcast_loss(
                pred_dbz, pred_lightning, y_dbz, y_lightning,
                reflect_mean=REFLECT_MEAN, reflect_std=REFLECT_STD,
            )
            loss.backward()
            optim.step()
            running += loss.item()
        print(f"epoch {epoch+1}/{epochs}  loss={running/len(loader):.4f}")

    torch.save(model.state_dict(), "vajra_nowcast.pt")
    print("Saved weights to vajra_nowcast.pt")
    return model


if __name__ == "__main__":
    train(epochs=3, batch_size=2)  # small smoke-test run; raise epochs/batch for real training
